//! The state-machine catalog is published twice as checked-in files: JSON for
//! the CLI / MCP tools and a Markdown reference page for people. This test
//! keeps both identical to what the engine's own transition rules say, so
//! the published graphs cannot drift.
//!
//! Regenerate after changing a transition rule or adding a machine:
//!
//! ```text
//! UPDATE_STATE_MACHINES=1 cargo test -p stateset-core --test state_machine_catalog
//! ```

use std::path::PathBuf;

use stateset_core::state_machine::catalog;

use stateset_core::state_machine::StateMachineDescriptor;

fn repo_file(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join(relative)
}

fn rendered_json() -> String {
    let mut json = serde_json::to_string_pretty(&serde_json::json!({
        "generated_by": "cargo test -p stateset-core --test state_machine_catalog",
        "machines": catalog(),
    }))
    .expect("catalog serialises");
    json.push('\n');
    json
}

fn rendered_markdown() -> String {
    let machines = catalog();
    let mut out = String::from(
        "# State Machines (generated)\n\n\
         <!-- Generated by `UPDATE_STATE_MACHINES=1 cargo test -p stateset-core --test \
         state_machine_catalog`. Do not edit. -->\n\n\
         Every status lifecycle whose transition rule is owned by the engine type itself \
         (`stateset_core::StateMachine`). These graphs are generated from the rules the \
         repositories enforce, so they are what the engine will accept.\n\n\
         A status reached only through an operation (shipping an order, capturing a payment) \
         still needs that operation; a plain status update may be refused even where an edge \
         exists here.\n\n\
         Ask the same question at runtime:\n\n\
         - Rust: `OrderStatus::Pending.next_states()`, `.check_transition(next)`, \
         `stateset_core::state_machine::catalog()`\n\
         - MCP / agents: the `explain_state_machine` tool\n\
         - CLI: `stateset explain state-machine machine=order from=pending to=delivered`\n\n\
         | Machine | Domain | Rust type | Initial | Terminal states |\n\
         | --- | --- | --- | --- | --- |\n",
    );
    for m in &machines {
        let terminal: Vec<&str> =
            m.states.iter().filter(|s| s.terminal).map(|s| s.name.as_str()).collect();
        out.push_str(&format!(
            "| [`{}`](#{}) | {} | `{}` | `{}` | {} |\n",
            m.name,
            m.name,
            m.domain,
            m.rust_type,
            m.initial,
            terminal.join(", ")
        ));
    }
    for m in &machines {
        out.push_str(&section(m));
    }
    out
}

fn section(m: &StateMachineDescriptor) -> String {
    let mut out = format!("\n## {}\n\n```mermaid\n{}```\n\n", m.name, m.to_mermaid());
    out.push_str("| From | Allowed next |\n| --- | --- |\n");
    for state in &m.states {
        let next = if state.terminal { "_terminal_".to_owned() } else { state.next.join(", ") };
        out.push_str(&format!("| `{}` | {} |\n", state.name, next));
    }
    out
}

#[test]
fn published_catalog_matches_the_engine() {
    let outputs = [
        ("cli/src/generated/state-machines.json", rendered_json()),
        ("docs/src/appendix/state-machines.md", rendered_markdown()),
    ];
    let update = std::env::var_os("UPDATE_STATE_MACHINES").is_some();

    for (relative, expected) in outputs {
        let path = repo_file(relative);
        if update {
            std::fs::create_dir_all(path.parent().expect("parent dir")).expect("create dir");
            std::fs::write(&path, &expected).expect("write catalog");
            continue;
        }

        // The CLI and docs trees are absent when the crate is built from a
        // crates.io tarball; there is nothing to compare against there.
        let Ok(actual) = std::fs::read_to_string(&path) else {
            eprintln!("skipping: {} not present", path.display());
            continue;
        };

        assert!(
            actual == expected,
            "{relative} is stale. Regenerate with:\n  UPDATE_STATE_MACHINES=1 cargo test -p \
             stateset-core --test state_machine_catalog"
        );
    }
}
