/**
 * Build a runtime list that names every member of `T` and nothing else. A
 * missing member makes the argument `never`; an extra one fails `readonly T[]`.
 */
function vocabulary<T extends string>() {
  return <const L extends readonly T[]>(list: L & ([T] extends [L[number]] ? unknown : never)): L =>
    list;
}

