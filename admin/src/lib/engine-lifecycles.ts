/**
 * Engine lifecycle vocabulary for the admin.
 *
 * The single place the admin learns which statuses a record can be in and
 * which moves the engine accepts. Nothing here is invented:
 *
 *  - Status unions are DERIVED from the native binding's declared types
 *    (`bindings/node/index.d.ts`, re-exported by `@stateset/embedded`). A
 *    status the engine adds or renames is a compile error in this file, not a
 *    badge that silently stops matching.
 *  - Several domains render the Rust `Debug` form (PascalCase: lots, serials,
 *    quality, waves, picks, receipts, bills, credit memos, GL accounts and
 *    journal entries). `embedded.ts` normalises those to the engine's
 *    canonical snake_case once, at the boundary, with `normalizeEngineStatus`;
 *    `EngineSnake<T>` is the same conversion at the type level, so the admin's
 *    unions for those domains are still derived from the binding.
 *  - Allowed transitions are a copy of the engine's `StateMachine` catalog
 *    (`cli/src/generated/state-machines.json`, generated by
 *    `cargo test -p stateset-core --test state_machine_catalog`). The copy
 *    exists only because the catalog lives outside the Next.js project;
 *    `tests/unit/lib/engine-lifecycles.test.ts` fails when the two disagree.
 *  - Action rules the catalog does not cover (bill approval, AP/AR aging scope,
 *    which invoices accept a payment) cite the engine code they mirror.
 *
 * Client-safe: the binding import is type-only and erased at build time.
 */

