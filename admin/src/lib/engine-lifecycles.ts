// ============================================================================
// Casing
// ============================================================================

type SnakeChars<S extends string> = S extends `${infer C}${infer Rest}`
  ? `${C extends Lowercase<C> ? C : `_${Lowercase<C>}`}${SnakeChars<Rest>}`
  : S;

type StripLeadingUnderscore<S extends string> = S extends `_${infer Rest}` ? Rest : S;

/**
 * Type-level twin of {@link normalizeEngineStatus}: the engine's snake_case
 * spelling of a `Debug`-rendered variant (`'PartiallyPaid'` → `'partially_paid'`).
 * Already-snake literals pass through unchanged.
 */
export type EngineSnake<S extends string> = StripLeadingUnderscore<SnakeChars<S>>;

/**
 * Convert an engine enum value to its canonical snake_case spelling.
 *
 * Idempotent: snake_case input is returned unchanged, so it is safe to apply
 * to every record whether the binding rendered `Debug` (`'InProgress'`) or the
 * canonical form (`'in_progress'`). Non-string values pass through untouched.
 */
export function normalizeEngineStatus<T>(value: T): T {
  if (typeof value !== 'string') return value;
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase() as T;
}

