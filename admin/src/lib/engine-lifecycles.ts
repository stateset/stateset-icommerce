/** One state machine: its initial state and the states each state may move to. */
export interface Lifecycle<S extends string> {
  /** Catalog machine name (`state-machines.json` `name`). */
  readonly name: string;
  readonly initial: S;
  readonly next: { readonly [K in S]: readonly S[] };
}

