function isState<S extends string>(lifecycle: Lifecycle<S>, status: string): status is S {
  return Object.prototype.hasOwnProperty.call(lifecycle.next, status);
}

/** The states `from` may move to; empty for terminal or unknown states. */
export function nextStates<S extends string>(lifecycle: Lifecycle<S>, from: string): readonly S[] {
  return isState(lifecycle, from) ? lifecycle.next[from] : [];
}

/** Whether the engine accepts moving a record from `from` to `to`. */
export function canTransition<S extends string>(
  lifecycle: Lifecycle<S>,
  from: string,
  to: S,
): boolean {
  return nextStates(lifecycle, from).includes(to);
}

/** A terminal state accepts no further transitions. Unknown states are not terminal. */
export function isTerminal<S extends string>(lifecycle: Lifecycle<S>, status: string): boolean {
  return isState(lifecycle, status) && lifecycle.next[status].length === 0;
}

/** States a record can still leave: the "open" or "pending" work queue. */
export function openStates<S extends string>(lifecycle: Lifecycle<S>): S[] {
  return (Object.keys(lifecycle.next) as S[]).filter((status) => !isTerminal(lifecycle, status));
}

